export function patternTokens(pattern: string): { text: string; ink: CardInk }[] {
  return pattern.split(' ').map(token => ({ text: token.replace(/^[gr]/, ''), ink: token.startsWith('g') ? 'jade' : token.startsWith('r') ? 'red' : 'ink' }));
}
